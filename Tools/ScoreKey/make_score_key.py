"""Writes the leaderboard signing key into the game and into the Firestore rules.

The key must not be committed (the repository is public):
  python Tools/ScoreKey/make_score_key.py <key-file>
    writes Assets/Scripts/Online/ScoreKey.cs (git-ignored), with the key XOR-masked so it is not
    a plain string in the build, and Tools/ScoreKey/firestore.rules.publish (git-ignored): the
    rules of firebase/firestore.rules with the key in place of __SCORE_KEY__, ready to paste in
    the Firebase console.
  python Tools/ScoreKey/make_score_key.py --new <key-file>
    makes a new random key first. Changing the key needs new rules AND a new build at the same time.
"""
import os
import secrets
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def main(args):
    new = "--new" in args
    args = [a for a in args if a != "--new"]
    if len(args) != 1:
        sys.exit(__doc__)
    key_file = args[0]
    if new:
        with open(key_file, "w") as f:
            f.write(secrets.token_hex(32))
    with open(key_file) as f:
        key = f.read().strip()
    if not key or "'" in key or "\\" in key:
        sys.exit("bad key")

    mask = secrets.token_bytes(len(key))
    masked = bytes(c ^ m for c, m in zip(key.encode(), mask))
    as_list = lambda bs: ", ".join(str(b) for b in bs)
    with open(os.path.join(ROOT, "Assets", "Scripts", "Online", "ScoreKey.cs"), "w", newline="\n") as f:
        f.write(
            "// Generated by Tools/ScoreKey/make_score_key.py. Git-ignored: never commit it.\n"
            "namespace Online {\n"
            "    public static partial class ScoreSignature {\n"
            "        static partial void LoadKey(ref string key) {\n"
            "            byte[] a = { " + as_list(masked) + " };\n"
            "            byte[] b = { " + as_list(mask) + " };\n"
            "            char[] k = new char[a.Length];\n"
            "            for (int i = 0; i < a.Length; i++) k[i] = (char)(a[i] ^ b[i]);\n"
            "            key = new string(k);\n"
            "        }\n"
            "    }\n"
            "}\n")

    with open(os.path.join(ROOT, "firebase", "firestore.rules")) as f:
        rules = f.read()
    if "__SCORE_KEY__" not in rules:
        sys.exit("firebase/firestore.rules has no __SCORE_KEY__")
    with open(os.path.join(ROOT, "Tools", "ScoreKey", "firestore.rules.publish"), "w", newline="\n") as f:
        f.write(rules.replace("__SCORE_KEY__", key))
    print("wrote ScoreKey.cs and Tools/ScoreKey/firestore.rules.publish")


if __name__ == "__main__":
    main(sys.argv[1:])
